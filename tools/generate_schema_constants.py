"""Write mne_bids/_schema.py from the BIDS schema.

Usage::

    python tools/generate_schema_constants.py [SCHEMA]

``SCHEMA`` is the path or URL of the ``schema.json`` published with the BIDS
specification, by default the one of the latest stable BIDS version.
"""

# Authors: The MNE-BIDS developers
# SPDX-License-Identifier: BSD-3-Clause

import json
import sys
from pathlib import Path
from urllib.request import Request, urlopen

source = (
    sys.argv[1]
    if len(sys.argv) > 1
    else "https://bids-specification.readthedocs.io/en/stable/schema.json"
)
if "://" in source:
    # readthedocs refuses urllib's default User-Agent
    with urlopen(Request(source, headers={"User-Agent": "mne-bids"})) as fid:
        schema = json.load(fid)
else:
    schema = json.loads(Path(source).read_text(encoding="utf-8"))

# entities in the order they appear in a filename
entities = {
    key: schema["objects"]["entities"][key] for key in schema["rules"]["entities"]
}
suffixes = set()
todo = [schema["rules"]["files"]["raw"]]
while todo:  # walk the nested groups of file rules
    rule = todo.pop()
    suffixes.update(rule.get("suffixes", []))
    todo.extend(val for val in rule.values() if isinstance(val, dict))

lines = [
    '"""Constants from the BIDS schema.',
    "",
    f"BIDS {schema['bids_version']} (schema {schema['schema_version']}), from",
    source,
    "",
    "Generated by tools/generate_schema_constants.py, do not edit.",
    '"""',
    "",
    "# Authors: The MNE-BIDS developers",
    "# SPDX-License-Identifier: BSD-3-Clause",
    "",
    f"BIDS_VERSION = {json.dumps(schema['bids_version'])}",
    "",
    "# short name -> long name, in the order the entities appear in a filename",
    "ENTITIES = {",
    *(
        f"    {json.dumps(ent['name'])}: {json.dumps(key)},"
        for key, ent in entities.items()
    ),
    "}",
    "",
    '# short name -> "label" or "index"',
    "ENTITY_FORMATS = {",
    *(
        f"    {json.dumps(ent['name'])}: {json.dumps(ent['format'])},"
        for ent in entities.values()
    ),
    "}",
    "",
    "DATATYPES = (",
    *(
        f"    {json.dumps(value)},"
        for value in sorted(
            dt["value"] for dt in schema["objects"]["datatypes"].values()
        )
    ),
    ")",
    "",
    "# suffixes of the raw (not derived) data and metadata files",
    "RAW_SUFFIXES = (",
    *(f"    {json.dumps(suffix)}," for suffix in sorted(suffixes)),
    ")",
    "",
]
out_fname = Path(__file__).parents[1] / "mne_bids" / "_schema.py"
out_fname.write_text("\n".join(lines), encoding="utf-8")
print(f"Wrote {out_fname} (BIDS {schema['bids_version']})")
